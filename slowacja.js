/* =========================================================
   🇸🇰 SŁOWACJA
   TABLICE BEZ MOŻLIWOŚCI OKREŚLENIA MIASTA
   =========================================================

   Od 2023 roku wprowadzono nowy system tablic
   bez oznaczenia okresu.

   Przykład:

   AA 397ZN

   AA nie wskazuje miasta ani okresu.

   W naszym albumie:

   → brak miasta
   → brak odległości
   → 2 gwiazdki
   → niebieska karta
   ========================================================= */

const SLOWACJA_FIXED_STARS = {

    "AA": 2

};


/* =========================================================
   SPRAWDZANIE STAŁEJ RZADKOŚCI SŁOWACJI
   ========================================================= */

function getSlowacjaFixedStars(
    plate
) {

    if (!plate) {

        return null;

    }


    const cleanPlate =
        plate
            .toUpperCase()
            .replace(
                /[\s-]/g,
                ""
            );


    if (!cleanPlate) {

        return null;

    }


    const prefix =
        cleanPlate.substring(
            0,
            2
        );


    if (
        Object.prototype.hasOwnProperty.call(
            SLOWACJA_FIXED_STARS,
            prefix
        )
    ) {

        return SLOWACJA_FIXED_STARS[
            prefix
        ];

    }


    return null;

}


